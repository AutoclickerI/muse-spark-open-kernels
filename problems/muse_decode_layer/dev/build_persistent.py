"""Build self-contained persistent dense islands around the validated MoE v4."""
from pathlib import Path
import ast
import sys
from chain_sources import chained
from vendor import vendor
root = Path(__file__).resolve().parents[1]
base = (root/'cand_moe4_attn.py').read_text()
chain = '--chain' in sys.argv
moe6 = '--moe6' in sys.argv
if moe6:
 a=base.index('# Losslessly vendored MoE v4')
 b=base.index('def experts_v4(',a)
 base=base[:a] + '# MoE v6, H200 check eefecf1eeb724feb.\n'+vendor(root.parent/'muse_moe_w4a16/cand_v6.py','mv4_')+'\n\n'+base[b:]
if chain: base = chained(base)
native = ast.parse((root/'cand_native.py').read_text())
source = next(ast.literal_eval(n.value) for n in native.body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='pr_CUDA_SRC' for t in n.targets))
a = source.index('// Weight stream:')
b = source.index('\ntemplate <int NT, int TR, int U, int NA, int XP, int LD>\nvoid launch_t',a)
helper = source[a:b]
helper = helper.replace('__global__ void __launch_bounds__(256) skinny_kernel(', '__device__ __forceinline__ void dense_tile(')
helper = helper.replace('int WN, int WK) {', 'int WN, int WK, int pn, int ps, int pt, float* sred) {')
helper = helper.replace('  extern __shared__ float sred[];\n', '')
helper = helper.replace('blockIdx.x', 'pn').replace('blockIdx.y','ps').replace('blockIdx.z','pt')
# Activations can have been written by a preceding phase of this very kernel.
helper = helper.replace('ld.global.nc.v4.u32','ld.global.cg.v4.u32')
helper = helper.replace('  for (int e = threadIdx.x; e < E; e += blockDim.x) {\n    const int tok = e / BR, row = e - tok * BR;\n    if (tok0 + tok < M) store(tok, row, sred[tok * S + row]);\n  }', '  for (int e = threadIdx.x; e < E; e += blockDim.x) {\n    const int tok = e / BR, row = e - tok * BR;\n    if (tok0 + tok < M) store(tok, row, sred[tok * S + row]);\n  }\n  __syncthreads();')
cu = (root/'dev/persistent.cu').read_text().replace('// DENSE_TILE_HELPERS',helper)
addon = (root/'dev/persistent_runtime.py').read_text()
out = base + '\n\n# Persistent dense islands: generated by dev/build_persistent.py.\nPERSIST_CUDA = r\"\"\"\n'+cu+'\n\"\"\"\n'+addon
target = root / ('cand_chain6.py' if moe6 else 'cand_chain.py' if chain else 'cand_persistent.py')
if '--occ2' in sys.argv:
 out=out.replace('__launch_bounds__(256, 1) dense_island','__launch_bounds__(256, NT == 1 ? 2 : 1) dense_island')
 out=out.replace("state['dense_grid'] = torch.cuda.get_device_properties(weights['o'].device).multi_processor_count","state['dense_grid'] = 2 * torch.cuda.get_device_properties(weights['o'].device).multi_processor_count")
 target=root/'cand_chain_occ2.py'
elif '--nopf' in sys.argv:
 out=out.replace('PERSIST_PREFETCH = True','PERSIST_PREFETCH = False')
 target=root/'cand_chain_nopf.py'
target.write_text(out)
print(target)
