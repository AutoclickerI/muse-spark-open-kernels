"""Generate prof/lab/ramp_oracle.py: S10's GEMV, sum+cast, attention exts and cluster glue (verbatim from
cand_r3_best7_s10.py) + gemv_bal's _gb_kernel + chain.py (shared chain pieces) + lab_body.py."""
import ast
import hashlib
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(HERE.parent / 'gemv_bal'))
import patch_gemv_bal  # noqa: E402

SRC = REPO / 'problems/muse_decode_layer/cand_r3_best7_s10.py'
OUT = REPO / 'prof/lab/ramp_oracle.py'

src = SRC.read_text()
lines = src.splitlines()
want = ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel', '_attn_sumcast_kernel', '_attn_main_plan', '_splits')
names = {'GLUE_CL_CUDA': 'RO_GLUE_CUDA', 'GLUE_CL_CPP': 'RO_GLUE_CPP', 'ATTN_PORT_CUDA_SRC': 'RO_PORT_CUDA',
         'ATTN_PORT_CPP_SRC': 'RO_PORT_CPP', 'CUDA_SRC': 'RO_LAYER_CUDA', 'CPP_SRC': 'RO_LAYER_CPP'}
funcs, vals = {}, {}
for node in ast.parse(src).body:
    if isinstance(node, ast.FunctionDef) and node.name in want:
        first = min([d.lineno for d in node.decorator_list] + [node.lineno])
        funcs[node.name] = '\n'.join(lines[first - 1:node.end_lineno])
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and getattr(node.targets[0], 'id', None) in names:
        vals[names[node.targets[0].id]] = ast.literal_eval(node.value)
assert len(funcs) == len(want) and len(vals) == len(names), (funcs.keys(), vals.keys())
gb = patch_gemv_bal.KERNEL
gb = gb[gb.index('@triton.jit'):gb.index('def _gb_gemv')].rstrip() + '\n'
head = ['"""Ramp oracle: L2-warm ceilings and pre-wait prefetch recipes per weight-streaming boundary of S10\'s '
        'small-M chain (generated by problems/muse_bf16_proj/dev/ramp_oracle/build.py from cand_r3_best7_s10.py, '
        'SHA-256 ' + hashlib.sha256(src.encode()).hexdigest() + ')."""',
        'import torch', 'import triton', 'import triton.language as tl', '']
head += [f'{k} = {v!r}' for k, v in sorted(vals.items())] + ['']
head += [funcs[n] + '\n' for n in want] + [gb]
OUT.write_text('\n'.join(head) + '\n\n' + (HERE / 'chain.py').read_text() + '\n\n' + (HERE / 'lab_body.py').read_text())
print(OUT, OUT.stat().st_size, hashlib.sha256(OUT.read_bytes()).hexdigest())
