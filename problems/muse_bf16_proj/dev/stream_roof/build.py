"""Generate prof/lab/stream_roof.py from roof.cu + lab_body.py."""
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parents[3] / 'prof/lab/stream_roof.py'
head = ['"""Cold-read recipes per dense weight size on the H200 (generated by problems/muse_bf16_proj/dev/stream_roof/build.py)."""',
        f"SR_CUDA = {(HERE / 'roof.cu').read_text()!r}", '']
OUT.write_text('\n'.join(head) + '\n' + (HERE / 'lab_body.py').read_text())
print(OUT, OUT.stat().st_size, hashlib.sha256(OUT.read_bytes()).hexdigest())
