"""Generate prof/lab/gemv_bal.py: S8's Triton GEMV (control, verbatim) + lab_body.py."""
import ast
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
SRC = REPO / 'problems/muse_decode_layer/cand_r3_best7_s8.py'
OUT = REPO / 'prof/lab/gemv_bal.py'

src = SRC.read_text()
lines = src.splitlines()
funcs = {}
for node in ast.parse(src).body:
    if isinstance(node, ast.FunctionDef) and node.name in ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel'):
        first = min([d.lineno for d in node.decorator_list] + [node.lineno])
        funcs[node.name] = '\n'.join(lines[first - 1:node.end_lineno])
assert len(funcs) == 4, funcs.keys()
head = ['"""Balanced split-K GEMV vs S8\'s Triton GEMV on the H200 (generated by problems/muse_bf16_proj/dev/gemv_bal/'
        'build.py from cand_r3_best7_s8.py, SHA-256 ' + hashlib.sha256(src.encode()).hexdigest() + ')."""',
        'import torch', 'import triton', 'import triton.language as tl', '']
head += [funcs[n] + '\n' for n in ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel')]
OUT.write_text('\n'.join(head) + '\n\n' + (HERE / 'lab_body.py').read_text())
print(OUT, OUT.stat().st_size, hashlib.sha256(OUT.read_bytes()).hexdigest())
