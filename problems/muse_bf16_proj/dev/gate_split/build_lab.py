"""Generate prof/lab/gate_split.py (the gate split's paired chain) and s10_gb_gs.py (S10 + patch_gemv_bal +
patch_gate_split, for local screens): S10's pieces as ramp_oracle/build.py takes them, the patched attention exts
and _gate_split_kernel from s10_gb_gs, + ../ramp_oracle/chain.py + lab_body.py."""
import ast
import hashlib
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path[:0] = [str(HERE), str(HERE.parent / 'gemv_bal')]
import patch_gate_split  # noqa: E402
import patch_gemv_bal  # noqa: E402

SRC = REPO / 'problems/muse_decode_layer/cand_r3_best7_s10.py'
NAME = sys.argv[1] if len(sys.argv) > 1 else 'gate_split'  # e.g. gate_sweep with an arms literal in argv[2]
OUT = REPO / f'prof/lab/{NAME}.py'
CAND = HERE / 's10_gb_gs.py'


def pieces(src, want, names):
    lines = src.splitlines()
    funcs, vals = {}, {}
    for node in ast.parse(src).body:
        if isinstance(node, ast.FunctionDef) and node.name in want:
            first = min([d.lineno for d in node.decorator_list] + [node.lineno])
            funcs[node.name] = '\n'.join(lines[first - 1:node.end_lineno])
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and getattr(node.targets[0], 'id', None) in names:
            vals[names[node.targets[0].id]] = ast.literal_eval(node.value)
    assert len(funcs) == len(want) and len(vals) == len(names), (funcs.keys(), vals.keys())
    return funcs, vals


src = SRC.read_text()
cand = patch_gate_split.patch(patch_gemv_bal.patch(src))
CAND.write_text(cand)
want = ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel', '_attn_sumcast_kernel', '_attn_main_plan', '_splits')
funcs, vals = pieces(src, want, {'GLUE_CL_CUDA': 'RO_GLUE_CUDA', 'GLUE_CL_CPP': 'RO_GLUE_CPP',
                                 'ATTN_PORT_CUDA_SRC': 'RO_PORT_CUDA', 'ATTN_PORT_CPP_SRC': 'RO_PORT_CPP',
                                 'CUDA_SRC': 'RO_LAYER_CUDA', 'CPP_SRC': 'RO_LAYER_CPP'})
gfuncs, gvals = pieces(cand, ('_gb_kernel', '_gate_split_kernel'),
                       {'ATTN_PORT_CUDA_SRC': 'RO_PORT_CUDA_GS', 'CUDA_SRC': 'RO_LAYER_CUDA_GS'})
head = ['"""Gate split chain vs S10 + gemv_bal at every q_len 1 shape (generated by '
        'problems/muse_bf16_proj/dev/gate_split/build_lab.py from cand_r3_best7_s10.py, SHA-256 '
        + hashlib.sha256(src.encode()).hexdigest() + '; patched: SHA-256 ' + hashlib.sha256(cand.encode()).hexdigest()
        + ')."""', 'import torch', 'import triton', 'import triton.language as tl', '']
head += [f'{k} = {v!r}' for k, v in sorted({**vals, **gvals}.items())] + ['']
head += [funcs[n] + '\n' for n in want] + [gfuncs[n] + '\n' for n in ('_gb_kernel', '_gate_split_kernel')]
body = (HERE / 'lab_body.py').read_text()
if len(sys.argv) > 2:  # replace the gate arms: [(name, (BN, S, NS)), ...]
    old = body[body.index('GS_ARMS = '):].split('\n', 1)[0]
    body = body.replace(old, f'GS_ARMS = {tuple(ast.literal_eval(sys.argv[2]))!r}')
OUT.write_text('\n'.join(head) + '\n\n' + (HERE.parent / 'ramp_oracle/chain.py').read_text() + '\n\n' + body)
print(CAND, hashlib.sha256(cand.encode()).hexdigest())
print(OUT, OUT.stat().st_size, hashlib.sha256(OUT.read_bytes()).hexdigest())
