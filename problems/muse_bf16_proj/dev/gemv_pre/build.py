"""Generate prof/lab/gemv_pre.py: S8's GEMV + glue_cl.cu (verbatim from cand_r3_best7_s8.py) + lab_body.py."""
import ast
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
SRC = REPO / 'problems/muse_decode_layer/cand_r3_best7_s8.py'
OUT = REPO / 'prof/lab/gemv_pre.py'

src = SRC.read_text()
lines = src.splitlines()
want = ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel')
funcs, vals = {}, {}
for node in ast.parse(src).body:
    if isinstance(node, ast.FunctionDef) and node.name in want:
        first = min([d.lineno for d in node.decorator_list] + [node.lineno])
        funcs[node.name] = '\n'.join(lines[first - 1:node.end_lineno])
    if isinstance(node, ast.Assign) and getattr(node.targets[0], 'id', None) in ('GLUE_CL_CUDA', 'GLUE_CL_CPP'):
        vals[node.targets[0].id] = ast.literal_eval(node.value)
assert len(funcs) == len(want) and len(vals) == 2, (funcs.keys(), vals.keys())
head = ['"""Balanced split-K GEMVs in their S8 chains (pool_router with pre-wait loads, qkv, the gate split, unpooler) '
        '(generated by problems/muse_bf16_proj/dev/gemv_pre/build.py from cand_r3_best7_s8.py, SHA-256 '
        + hashlib.sha256(src.encode()).hexdigest() + ')."""',
        'import torch', 'import triton', 'import triton.language as tl', '',
        f"GP_CUDA = {vals['GLUE_CL_CUDA']!r}", f"GP_CPP = {vals['GLUE_CL_CPP']!r}", '']
head += [funcs[n] + '\n' for n in want]
OUT.write_text('\n'.join(head) + '\n\n' + (HERE / 'lab_body.py').read_text())
print(OUT, OUT.stat().st_size, hashlib.sha256(OUT.read_bytes()).hexdigest())
