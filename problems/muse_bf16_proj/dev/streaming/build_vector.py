"""Build the next lab: vector shared loads feed two MMA steps at a time."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE / "kernel.cu").read_text()
start = src.index("#pragma unroll\n    for (int k = 0; k < BK; k += 16)")
end = src.index("    __syncthreads();", start)
src = src[:start] + (HERE / "consumer_vector.cu.inc").read_text() + src[end:]
# A 128-bit shared transaction covers eight lanes/two operand rows. Give the
# second row the other half of the 32 banks. The scalar-fragment +8 pad is
# conflict-free for 32-bit LDS, but conflicts for this vector access pattern.
src = src.replace("BK + 8", "BK + 32")
out = HERE.parent / "streaming_gemv_vector_lab.py"
out.write_text(
    '"""Vector-consumer streaming projections: generated by dev/streaming/build_vector.py."""\n'
    + "SP_CUDA = " + repr(src) + "\n\n"
    + (HERE / "runtime.py.inc").read_text() + "\n\n"
    + (HERE / "lab.py.inc").read_text()
)
print(out)
