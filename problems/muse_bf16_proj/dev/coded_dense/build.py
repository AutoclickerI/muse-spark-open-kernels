"""Generate the P10 lab payloads.

    python3 problems/muse_bf16_proj/dev/coded_dense/build.py
    tools/img python problems/muse_bf16_proj/dev/coded_dense/local_lab.py prof/lab/coded_gemv.py    # screen in the image
    tools/img python problems/muse_bf16_proj/dev/coded_dense/local_lab.py prof/lab/coded_chain.py

prof/lab/coded_gemv.py  = S8's Triton GEMV (control, verbatim) + coded.py + lab_body.py (standalone sweep).
prof/lab/coded_chain.py = the same + S8's glue_cl kernels + P7's chain harness (../gemv_pre/lab_body.py without its
                          lab()) + chain_body.py with CC_CFG (the standalone winners) filled in.
"""
import ast
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
SRC = REPO / 'problems/muse_decode_layer/cand_r3_best7_s8.py'

# (t, role) -> [(NW, RT, PIPE, S, V, C), ...]: H200 coded_gemv winners for the chain lab.
CC_CFG = {(t, r): [(8, 1, 2, 11 if r == 'pool_router' else 22 if r == 'qkv' else 8 if r == 'o' else 16, 3, 1)]
          for t in (1, 8, 16, 32) for r in ('qkv', 'pool_router', 'o', 'unpool_slice' if t <= 8 else 'unpooler')}  # provisional

src = SRC.read_text()
lines = src.splitlines()
want = ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel')
funcs, vals = {}, {}
for node in ast.parse(src).body:
    if isinstance(node, ast.FunctionDef) and node.name in want:
        first = min([d.lineno for d in node.decorator_list] + [node.lineno])
        funcs[node.name] = '\n'.join(lines[first - 1:node.end_lineno])
    if isinstance(node, ast.Assign) and getattr(node.targets[0], 'id', None) in ('GLUE_CL_CUDA', 'GLUE_CL_CPP'):
        vals[node.targets[0].id] = ast.literal_eval(node.value)
assert len(funcs) == len(want) and len(vals) == 2, (funcs.keys(), vals.keys())
coded = (HERE / 'coded.py').read_text()
body = coded.split('import torch.nn.functional as F\n', 1)[1]
tag = (f'S8 SHA-256 {hashlib.sha256(src.encode()).hexdigest()}, coded.py SHA-256 '
       f'{hashlib.sha256(coded.encode()).hexdigest()}')
imports = ['import torch', 'import torch.nn.functional as F', 'import triton', 'import triton.language as tl', '']
s8 = [funcs[n] + '\n' for n in want]
# Kernel steps paired by the standalone lab (the first is the reference) and the (NW, RT, PIPE) shapes it sweeps.
CL_VS = (1, 2, 3)
CL_SHAPES = ((8, 1, 2), (8, 1, 4), (4, 2, 2))
lab_body = (HERE / 'lab_body.py').read_text().replace('__CL_VS__', repr(CL_VS)).replace('__CL_SHAPES__', repr(CL_SHAPES))


def write(out, text):
    out.write_text(text)
    print(out, out.stat().st_size, hashlib.sha256(out.read_bytes()).hexdigest())


write(REPO / 'prof/lab/coded_gemv.py',
      '\n'.join(['"""Coded (12-bit lossless) dense GEMV vs S8 / P7 BF16 GEMVs on the H200 (generated by '
                 f'problems/muse_bf16_proj/dev/coded_dense/build.py; {tag})."""'] + imports + s8)
      + '\n' + body + '\n\n' + lab_body)

if CC_CFG:
    pre = (REPO / 'problems/muse_bf16_proj/dev/gemv_pre/lab_body.py').read_text().split('\ndef lab(', 1)[0]
    tree = ast.parse(lab_body)
    cl_w = next('\n'.join(lab_body.splitlines()[n.lineno - 1:n.end_lineno]) for n in tree.body
                if isinstance(n, ast.FunctionDef) and n.name == 'cl_weights')
    chain = (HERE / 'chain_body.py').read_text().replace('__CC_CFG__', repr(CC_CFG))
    write(REPO / 'prof/lab/coded_chain.py',
          '\n'.join(['"""Coded dense GEMVs in their S8/S10 chains vs S8 and P7 controls (generated by '
                     f'problems/muse_bf16_proj/dev/coded_dense/build.py; {tag})."""', 'import math'] + imports
                    + [f"GP_CUDA = {vals['GLUE_CL_CUDA']!r}", f"GP_CPP = {vals['GLUE_CL_CPP']!r}", ''] + s8)
          + '\n' + body + '\n\n' + pre + '\n\n' + cl_w + '\n' + chain)

# (tokens, role) -> (NW, RT, PIPE, S, prew, V, C) for the whole-layer A/B on the decode host (main sends it).
CL_ROWS = {**{(t, 'qkv_gate'): (8, 1, 2, 22, 1, 3, 1) for t in (1, 8, 16, 32)},
           **{(t, 'pool_router'): (8, 1, 2, 11, 1, 3, 1) for t in (1, 8, 16, 32)},
           **{(t, 'o'): (8, 1, 2, 8, 0, 3, 1) for t in (1, 8, 16, 32)},
           **{(t, 'unpooler_slice'): (8, 1, 2, 16, 1, 3, 1) for t in (1, 8)},
           **{(t, 'unpooler'): (8, 1, 2, 8, 1, 3, 1) for t in (16, 32)}}  # provisional
if CL_ROWS:
    write(REPO / 'prof/lab/coded_layer.py',
          '\n'.join(['"""Whole-layer paired A/B of the coded dense GEMVs on the decode host\'s prepared state (generated by '
                     f'problems/muse_bf16_proj/dev/coded_dense/build.py; {tag})."""'] + imports)
          + '\n' + body + '\n\n' + (HERE / 'layer_body.py').read_text().replace('__CL_ROWS__', repr(CL_ROWS)))
