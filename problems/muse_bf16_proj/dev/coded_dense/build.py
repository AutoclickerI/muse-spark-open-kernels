"""Generate prof/lab/coded_gemv.py: S8's Triton GEMV (control, verbatim) + coded.py + lab_body.py.

    python3 problems/muse_bf16_proj/dev/coded_dense/build.py
    CUDA_VISIBLE_DEVICES=0 python3 problems/muse_bf16_proj/dev/coded_dense/local_lab.py prof/lab/coded_gemv.py
"""
import ast
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
SRC = REPO / 'problems/muse_decode_layer/cand_r3_best7_s8.py'
OUT = REPO / 'prof/lab/coded_gemv.py'

src = SRC.read_text()
lines = src.splitlines()
funcs = {}
for node in ast.parse(src).body:
    if isinstance(node, ast.FunctionDef) and node.name in ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel'):
        first = min([d.lineno for d in node.decorator_list] + [node.lineno])
        funcs[node.name] = '\n'.join(lines[first - 1:node.end_lineno])
assert len(funcs) == 4, funcs.keys()
coded = (HERE / 'coded.py').read_text()
head = ['"""Coded (12-bit lossless) dense GEMV vs S8 / P7 BF16 GEMVs on the H200 (generated by '
        'problems/muse_bf16_proj/dev/coded_dense/build.py; S8 SHA-256 ' + hashlib.sha256(src.encode()).hexdigest()
        + ', coded.py SHA-256 ' + hashlib.sha256(coded.encode()).hexdigest() + ')."""',
        'import torch', 'import torch.nn.functional as F', 'import triton', 'import triton.language as tl', '']
head += [funcs[n] + '\n' for n in ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel')]
body = coded.split('import torch.nn.functional as F\n', 1)[1]
OUT.write_text('\n'.join(head) + '\n' + body + '\n\n' + (HERE / 'lab_body.py').read_text())
print(OUT, OUT.stat().st_size, hashlib.sha256(OUT.read_bytes()).hexdigest())
