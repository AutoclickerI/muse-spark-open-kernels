"""Emit the standalone verify GEMM lab and decode dispatch block."""
from pathlib import Path
import ast

HERE = Path(__file__).resolve().parent
cuda = (HERE / 'kernel.cu').read_text()
configs = {
    0: (64,64,64,8,False), 1: (64,128,64,6,False),
    2: (64,128,64,8,True), 3: (64,128,128,4,True),
    4: (128,128,64,6,True), 5: (128,128,128,3,True),
    6: (256,128,64,4,True), 7: (64,256,64,5,True),
    8: (128,256,64,4,True), 9: (64,64,128,6,True),
    10: (64,128,64,6,True), 11: (128,128,64,6,False),
    12: (128,64,64,8,True), 13: (256,64,64,5,True),
    14: (64,128,256,2,True),
}
cases = []
for code, (bm,bn,bk,st,pipe) in configs.items():
    # sm120 has less shared memory. Preserve at least two slots and each consumer.
    lbk, lst = bk, st
    while (bm+bn)*lbk*2*2 + 32 > 101376:
        lbk //= 2
    while (bm+bn)*lbk*2*lst + lst*16 > 101376:
        lst -= 1
    cases.append(f'''  if (code == {code}) {{
#ifdef VS_LOCAL
    return launch<{bm},{bn},{lbk},{lst},{str(pipe).lower()}>(w,x,out,partial,count,m,n,k,splits,fp32,(cudaStream_t)stream,descriptor_only);
#else
    return launch<{bm},{bn},{bk},{st},{str(pipe).lower()}>(w,x,out,partial,count,m,n,k,splits,fp32,(cudaStream_t)stream,descriptor_only);
#endif
  }}''')
cuda = cuda.replace('// VS_CONFIG_CASES', '\n'.join(cases))
# Generate the fixed-width instruction bindings, keeping register lists auditable.
ops = []
for n in (64, 128, 256):
    regs = n // 2
    operands = ', '.join('%' + str(i) for i in range(regs))
    outputs = ', '.join(f'"+f"(d[{i}])' for i in range(regs))
    ops.append(f'''__device__ __forceinline__ void wg{n}(float (&d)[{regs}], uint64_t a, uint64_t b) {{
  asm volatile("{{ .reg .pred p; setp.ne.b32 p, 1, 0; "
      "wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16 {{{operands}}}, %{regs}, %{regs+1}, p, 1, 1, 0, 0; }}"
      : {outputs} : "l"(a), "l"(b));
}}''')
cuda = cuda.replace('// WGMMA_BINDINGS', '\n'.join(ops))
module = '"""Weight-wide TMA/WGMMA projections; generated by verify_streaming/build.py."""\n'
module += 'VS_CONFIGS = ' + repr(configs) + '\nVS_CUDA = ' + repr(cuda) + '\n\n' + (HERE / 'runtime.py.inc').read_text()
(HERE / 'projection.py').write_text(module)
best6 = HERE.parents[2] / 'muse_decode_layer' / 'cand_r3_best6.py'
source = best6.read_text()
tree = ast.parse(source)
names = {'_PgNative','PG_RAW','_l2_prefetch','_pdl_start','_pdl_wait','_launch','_gemv_kernel','gemv','GEMV_CFG'}
control = ['import ctypes as ct\nimport torch.nn.functional as F\nimport triton\nimport triton.language as tl\n'
           'HIDDEN=8192\nD_EXPERT=4096\nQ_SIZE=1024\nQKV_SIZE=2304\nN_EXPERTS=256\nUNPOOL_SLICE=1024\n'
           'PDL=True\nPREFETCH=True\nGEMV_MAX_T=64\n'
           '_GEMV_CHOICES={(8,4608,8192):(32,1024,128,False),(8,1024,4096):(64,512,128,False)}\n']
for node in tree.body:
    ids = {getattr(t,'id',None) for t in node.targets} if isinstance(node,ast.Assign) else {getattr(node,'name',None)}
    if ids & names:
        lo = min([node.lineno] + [d.lineno for d in getattr(node,'decorator_list',[])])
        control.append('\n'.join(source.splitlines()[lo-1:node.end_lineno]))
control.append('VS_BEST6_SHA256 = ' + repr(__import__('hashlib').sha256(source.encode()).hexdigest()))
(HERE.parent / 'verify_streaming_lab.py').write_text(module + '\n\n' + '\n\n'.join(control)
                                                   + '\n\n' + (HERE / 'lab.py.inc').read_text())
print('generated projection.py and ../verify_streaming_lab.py')
