"""Generate prof/lab/glue_big.py: S10's _boundary_fast (+ its PDL helpers, verbatim from cand_r3_best7_s10.py) +
lab_body.py (boundary glue variants at t = 128 / 256 behind their library-GEMM producers)."""
import ast
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
SRC = REPO / 'problems/muse_decode_layer/cand_r3_best7_s10.py'
OUT = REPO / 'prof/lab/glue_big.py'

src = SRC.read_text()
lines = src.splitlines()
want = ('_pdl_start', '_pdl_wait', '_boundary_fast')
funcs = {}
for node in ast.parse(src).body:
    if isinstance(node, ast.FunctionDef) and node.name in want:
        first = min([d.lineno for d in node.decorator_list] + [node.lineno])
        funcs[node.name] = '\n'.join(lines[first - 1:node.end_lineno])
assert len(funcs) == len(want), funcs.keys()
head = ['"""Boundary glue at t = 128 / 256 (generated by problems/muse_bf16_proj/dev/glue_big/build.py from '
        'cand_r3_best7_s10.py, SHA-256 ' + hashlib.sha256(src.encode()).hexdigest() + ')."""',
        'import torch', 'import triton', 'import triton.language as tl', '']
head += [funcs[n] + '\n' for n in want]
OUT.write_text('\n'.join(head) + '\n\n' + (HERE / 'lab_body.py').read_text())
print(OUT, OUT.stat().st_size, hashlib.sha256(OUT.read_bytes()).hexdigest())
