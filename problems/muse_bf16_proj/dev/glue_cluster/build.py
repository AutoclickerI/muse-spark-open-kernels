"""Generate prof/lab/glue_cluster.py: S6's Triton glue + GEMV sources (exact) + glue_cl.cu + lab_body.py."""
import ast
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
S6 = REPO / 'problems/muse_decode_layer/cand_r3_best7_s6.py'
OUT = REPO / 'prof/lab/glue_cluster.py'

src = S6.read_text()
lines = src.splitlines()
want = ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel', '_boundary_fast', '_route_fast')
funcs = {}
for node in ast.parse(src).body:
    if isinstance(node, ast.FunctionDef) and node.name in want:
        first = min([d.lineno for d in node.decorator_list] + [node.lineno])
        funcs[node.name] = '\n'.join(lines[first - 1:node.end_lineno])
assert len(funcs) == len(want), funcs.keys()
cuda = (HERE / 'glue_cl.cu').read_text()
head = ['"""Cluster glue vs S6 Triton glue on the H200 (generated by problems/muse_bf16_proj/dev/glue_cluster/'
        'build.py from cand_r3_best7_s6.py, SHA-256 ' + hashlib.sha256(src.encode()).hexdigest() + ')."""',
        'import torch', 'import triton', 'import triton.language as tl', '', f'GC_CUDA = {cuda!r}', '']
head += [funcs[n] + '\n' for n in want]
OUT.write_text('\n'.join(head) + '\n\n' + (HERE / 'lab_body.py').read_text())
print(OUT, OUT.stat().st_size, hashlib.sha256(OUT.read_bytes()).hexdigest())
