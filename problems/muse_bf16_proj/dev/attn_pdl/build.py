"""Generate prof/lab/attn_pdl_o.py: S6's exact attention (attn_main) and O cell (GF) sources + lab body."""
import ast
import hashlib
import pathlib
import re

REPO = pathlib.Path(__file__).resolve().parents[4]
S6 = REPO / "problems/muse_decode_layer/cand_r3_best7_s6.py"
BODY = pathlib.Path(__file__).with_name("lab_body.py")
OUT = REPO / "prof/lab/attn_pdl_o.py"

src = S6.read_text()
tree = ast.parse(src)
want = {"ATTN_PORT_CUDA_SRC", "ATTN_PORT_CPP_SRC", "GF_CUDA", "GF_CONFIGS"}
vals = {}
for node in tree.body:
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and getattr(node.targets[0], "id", None) in want:
        vals[node.targets[0].id] = ast.literal_eval(node.value)
assert set(vals) == want, set(vals)
head = ['"""Attention early PDL trigger + O weight prefetch on the H200 (generated by '
        'problems/muse_bf16_proj/dev/attn_pdl/build.py from cand_r3_best7_s6.py, SHA-256 '
        + hashlib.sha256(src.encode()).hexdigest() + ')."""']
for k in ("ATTN_PORT_CUDA_SRC", "ATTN_PORT_CPP_SRC", "GF_CUDA", "GF_CONFIGS"):
    head.append(f"AP_{k} = {vals[k]!r}")
OUT.write_text("\n".join(head) + "\n\n" + BODY.read_text())
print(OUT, OUT.stat().st_size, hashlib.sha256(OUT.read_bytes()).hexdigest())
