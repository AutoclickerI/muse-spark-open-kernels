"""Generate prof/lab/attn_front.py: S6's qkv GEMV (Triton source) and attn_main (base / partial-reading /
PDL / PDL + trigger, from patch_attn_front.py) + lab_body.py."""
import ast
import hashlib
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path[:0] = [str(HERE), str(HERE.parent / 'attn_pdl')]
import patch_attn_front  # noqa: E402
import patch_trigger  # noqa: E402

S6 = REPO / 'problems/muse_decode_layer/cand_r3_best7_s6.py'
OUT = REPO / 'prof/lab/attn_front.py'

src = S6.read_text()
tree = ast.parse(src)
lines = src.splitlines()
vals, funcs = {}, {}
for node in tree.body:
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and getattr(node.targets[0], 'id', None) in (
            'ATTN_PORT_CUDA_SRC', 'ATTN_PORT_CPP_SRC', 'CUDA_SRC', 'CPP_SRC'):
        vals[node.targets[0].id] = ast.literal_eval(node.value)
    if isinstance(node, ast.FunctionDef) and node.name in ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel'):
        first = min([d.lineno for d in node.decorator_list] + [node.lineno])
        funcs[node.name] = '\n'.join(lines[first - 1:node.end_lineno])
assert len(vals) == 4 and len(funcs) == 4, (vals.keys(), funcs.keys())
cuda, cpp = vals['ATTN_PORT_CUDA_SRC'], vals['ATTN_PORT_CPP_SRC']
pdl = patch_attn_front.patch_cuda(cuda, pdl=True)
trig_old, trig_new = patch_trigger.OLD, patch_trigger.NEW
assert pdl.count(trig_old) == 1
sources = {
    'base': (cuda, cpp),
    'pdl': (pdl, patch_attn_front.patch_cpp(cpp)),
    'trig': (pdl.replace(trig_old, trig_new), patch_attn_front.patch_cpp(cpp)),
}
head = ['"""qkv GEMV -> attn_main front on the H200 (generated by problems/muse_bf16_proj/dev/attn_front/build.py '
        'from cand_r3_best7_s6.py, SHA-256 ' + hashlib.sha256(src.encode()).hexdigest() + ')."""',
        'import torch', 'import triton', 'import triton.language as tl', '',
        f'AF_SOURCES = {sources!r}', f"AF_LAYER = {(vals['CUDA_SRC'], vals['CPP_SRC'])!r}", '']
head += [funcs[n] + '\n' for n in ('_l2_prefetch', '_pdl_start', '_pdl_wait', '_gemv_kernel')]
OUT.write_text('\n'.join(head) + '\n\n' + (HERE / 'lab_body.py').read_text())
print(OUT, OUT.stat().st_size, hashlib.sha256(OUT.read_bytes()).hexdigest())
