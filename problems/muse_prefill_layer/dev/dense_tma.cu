template<int BT,int BK,int ST>
__global__ void __launch_bounds__(256) mixed_kernel(
 const __grid_constant__ CUtensorMap tmW,const __grid_constant__ CUtensorMap tmX,
 __nv_bfloat16* __restrict__ Pool,float* __restrict__ Logits,int M){
#ifdef MP_TMA
 constexpr int BR=64,AB=BR*64*2,CB=(BR+BT)*64*2,SB=CB*(BK/64);
 extern __shared__ __align__(1024) unsigned char smem[];
 uint64_t* full=reinterpret_cast<uint64_t*>(smem+ST*SB);uint64_t* empty=full+ST;
 const int tid=threadIdx.x,consumer=tid<128;
 const int tile=blockIdx.x,row0=(tile%72)*64,tok0=(tile/72)*BT;
 const int steps=8192/BK,kb0=0,kx=8192;
    if (tid == 0) {
      for (int s = 0; s < ST; ++s) { mbar_init(full + s, 1); mbar_init(empty + s, 1); }
      asm volatile("fence.mbarrier_init.release.cluster;" ::: "memory");
      asm volatile("fence.proxy.async.shared::cta;" ::: "memory");
    }
    __syncthreads();
    float acc[BT / 2];
#pragma unroll
    for (int i = 0; i < BT / 2; ++i) acc[i] = 0.f;
    if (tid == 128) {
      for (int s = 0; s < steps; ++s) {
        int stage = s % ST;
        if (s >= ST) mbar_wait(empty + stage, ((s / ST) & 1) ^ 1);
        unsigned char* a = smem + stage * SB;
        mbar_expect_tx(full + stage, SB);
        int kc = (kb0 + s) * BK;
#pragma unroll
        for (int chunk_k=0; chunk_k<BK/64; ++chunk_k) {
          tma_load_2d(a+chunk_k*CB, &tmW, full + stage, kc+chunk_k*64, row0);
          tma_load_2d(a+chunk_k*CB+AB, &tmX, full + stage, (kc+chunk_k*64) % kx, tok0);
        }
      }
    } else if (consumer) {
      for (int s = 0; s < steps; ++s) {
        int stage = s % ST;
        mbar_wait(full + stage, (s / ST) & 1);
        unsigned char* a = smem + stage * SB;
#ifdef MP_SM90A
        acc_fence(acc);
        wgmma_fence();
#pragma unroll
        for (int kk = 0; kk < BK / 16; ++kk) {
          const uint64_t da = make_desc(a+(kk/4)*CB,64), db = make_desc(a+(kk/4)*CB+AB,64);
          if constexpr(BT==64) wgmma_m64n64(acc,da+2*(kk%4),db+2*(kk%4),1); else if constexpr(BT==128) wgmma_m64n128(acc,da+2*(kk%4),db+2*(kk%4),1); else if constexpr(BT==256) wgmma_m64n256(acc,da+2*(kk%4),db+2*(kk%4),1);
        }
        wgmma_commit();
        wgmma_wait<0>();
        acc_fence(acc);
#else
        const int warp = tid >> 5, ln = tid & 31;
#pragma unroll
        for (int kk = 0; kk < BK / 16; ++kk) {
          unsigned char* chunk_a=a+(kk/4)*CB;
          int ar = warp * 16 + (ln & 15), ac = (kk%4) * 2 + (ln >> 4);
          uint32_t a0,a1,a2,a3;
          ldsm_x4(chunk_a + ar * 128 + ((ac ^ (ar & 7)) << 4), a0,a1,a2,a3);
#pragma unroll
          for (int j = 0; j < BT / 8; ++j) {
            int br = j * 8 + (ln & 7), bc = (kk%4) * 2 + ((ln >> 3) & 1);
            uint32_t b0,b1;
            ldsm_x2(chunk_a + AB + br * 128 + ((bc ^ (br & 7)) << 4), b0,b1);
            mma_emu(&acc[4*j],a0,a1,a2,a3,b0,b1);
          }
        }
        asm volatile("bar.sync 1, 128;" ::: "memory");
#endif
        if (tid == 0) mbar_arrive(empty + stage);
      }
    }
    __syncthreads();

 if(consumer){
  int warp=tid>>5,lane=tid&31,row=warp*16+(lane>>2),col=2*(lane&3);
#pragma unroll
  for(int j=0;j<BT/8;++j){
#pragma unroll
   for(int q=0;q<4;++q){
    int r=row+(q>=2?8:0),t=j*8+col+(q&1),feature=row0+r;
    if(tok0+t<M){
     float v=acc[j*4+q];
     if(feature<4096)Pool[(size_t)(tok0+t)*4096+feature]=__float2bfloat16_rn(v);
     else Logits[(size_t)(tok0+t)*512+feature-4096]=v;
    }
   }
  }
 }
#endif
}

static PFN_cuTensorMapEncodeTiled_v12000 encode_fn() {
  static PFN_cuTensorMapEncodeTiled_v12000 fn = nullptr;
  if (!fn) {
    cudaDriverEntryPointQueryResult q;
    void* p = nullptr;
    cudaGetDriverEntryPoint("cuTensorMapEncodeTiled", &p, cudaEnableDefault, &q);
    TORCH_CHECK(p != nullptr, "cuTensorMapEncodeTiled unavailable");
    fn = reinterpret_cast<PFN_cuTensorMapEncodeTiled_v12000>(p);
  }
  return fn;
}

// 2D BF16 tensor map over a row-major [rows, cols] matrix, box [box_rows, 64], 128-byte swizzle.
static CUtensorMap make_map(const void* ptr, int rows, int cols, int box_rows, int bk) {
  CUtensorMap m;
  cuuint64_t dims[2] = {(cuuint64_t)cols, (cuuint64_t)rows};
  cuuint64_t strides[1] = {(cuuint64_t)cols * 2};
  cuuint32_t box[2] = {64, (cuuint32_t)box_rows};
  cuuint32_t es[2] = {1, 1};
  CUresult r = encode_fn()(&m, CU_TENSOR_MAP_DATA_TYPE_BFLOAT16, 2, const_cast<void*>(ptr), dims, strides,
                           box, es, CU_TENSOR_MAP_INTERLEAVE_NONE, CU_TENSOR_MAP_SWIZZLE_128B,
                           CU_TENSOR_MAP_L2_PROMOTION_L2_256B, CU_TENSOR_MAP_FLOAT_OOB_FILL_NONE);
  TORCH_CHECK(r == CUDA_SUCCESS, "cuTensorMapEncodeTiled failed: ", (int)r);
  return m;
}


template<int BT,int BK,int ST>
void mixed_launch(torch::Tensor W,torch::Tensor X,torch::Tensor Pool,torch::Tensor Logits){
 TORCH_CHECK(W.size(0)==4608 && W.size(1)==8192 && X.size(1)==8192,"mixed TMA shape");
 int M=X.size(0);size_t smem=ST*(64+BT)*BK*2+ST*16;
 auto kern=mixed_kernel<BT,BK,ST>;
 static bool initialized=false;
 if(!initialized){
  TORCH_CHECK(cudaFuncSetAttribute(kern,cudaFuncAttributeMaxDynamicSharedMemorySize,smem)==cudaSuccess,"mixed TMA shared memory");
  initialized=true;
 }
 CUtensorMap mw=make_map(W.data_ptr(),4608,8192,64,BK),mx=make_map(X.data_ptr(),M,8192,BT,BK);
 kern<<<72*((M+BT-1)/BT),256,smem,at::cuda::getCurrentCUDAStream()>>>(mw,mx,reinterpret_cast<__nv_bfloat16*>(Pool.data_ptr()),Logits.data_ptr<float>(),M);
 C10_CUDA_KERNEL_LAUNCH_CHECK();
}
} // namespace prefill_mixed
void mixed(torch::Tensor W,torch::Tensor X,torch::Tensor Pool,torch::Tensor Logits,int64_t code){
 using namespace prefill_mixed;
 if(code==0)mixed_launch<64,64,4>(W,X,Pool,Logits);
 else if(code==1)mixed_launch<128,64,4>(W,X,Pool,Logits);
 else if(code==2)mixed_launch<128,128,2>(W,X,Pool,Logits);
 else if(code==3)mixed_launch<256,64,2>(W,X,Pool,Logits);
 else TORCH_CHECK(false,"mixed TMA config");
}
