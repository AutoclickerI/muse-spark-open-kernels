#endif
}
template<int N> __device__ __forceinline__ void protect(float (&a)[N/2]){
#pragma unroll
 for(int j=0;j<N/2;++j)asm volatile("":"+f"(a[j])::"memory");
}
__device__ __forceinline__ void keep(uint32_t (&a)[4]){asm volatile(""::"r"(a[0]),"r"(a[1]),"r"(a[2]),"r"(a[3]));}
