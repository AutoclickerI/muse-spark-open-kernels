"""Generate the self-contained lab; namespace copied kernels without runtime repo imports."""
import ast
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent


def namespace(source, prefix):
    tree = ast.parse(source)
    names = set()
    def globals_in(nodes):
        for n in nodes:
            if isinstance(n, (ast.FunctionDef, ast.ClassDef)):
                names.add(n.name)
            elif isinstance(n, (ast.Import, ast.ImportFrom)):
                names.update(a.asname or a.name.split('.')[0] for a in n.names)
            elif isinstance(n, (ast.Assign, ast.AnnAssign)):
                targets = n.targets if isinstance(n, ast.Assign) else [n.target]
                for t in targets:
                    names.update(x.id for x in ast.walk(t) if isinstance(x, ast.Name))
            elif isinstance(n, (ast.Try, ast.If)):
                globals_in(n.body); globals_in(n.orelse)
                if isinstance(n, ast.Try):
                    globals_in(n.finalbody)
                    for h in n.handlers: globals_in(h.body)
    globals_in(tree.body)
    names.discard('annotations')
    rename = {n: prefix+n for n in names}
    class Rename(ast.NodeTransformer):
        def visit_Name(self,n):
            n.id=rename.get(n.id,n.id); return n
        def visit_Global(self,n):
            n.names=[rename.get(s,s) for s in n.names]; return n
        def visit_FunctionDef(self,n):
            n.name=rename.get(n.name,n.name); return self.generic_visit(n)
        def visit_ClassDef(self,n):
            n.name=rename.get(n.name,n.name); return self.generic_visit(n)
        def visit_Import(self,n):
            for a in n.names:
                key=a.asname or a.name.split('.')[0]
                if key in rename: a.asname=rename[key]
            return n
        def visit_ImportFrom(self,n):
            if n.module=='__future__': return None
            for a in n.names:
                key=a.asname or a.name
                if key in rename:a.asname=rename[key]
            return n
    return ast.unparse(ast.fix_missing_locations(Rename().visit(tree)))+'\n'


def segment(path, start=None, end=None):
    s=(ROOT/path).read_text()
    if start:s=s[s.index(start):]
    if end:s=s[:s.index(end)]
    return s


def build():
    p='problems/muse_moe_w4a16/'
    parts=[]
    sources=[
      ('v9_',p+'cand_v9.py',None,None),
      ('ph_',p+'cand_v9_phase.py',None,'\nimport json'),
      ('hu_',p+'cand_v11.py','\nimport json','\ndef _time_variant'),
      ('ho_',p+'cand_humming.py',None,None),
      ('v19_',p+'dev/parked/cand_v19.py',None,'\n# V9 is the native'),
      ('gr_','problems/muse_decode_layer/cand_r3_v9_cost_autotune.py','\nimport os\nimport triton\nimport triton.language as tl\n\nGROUPED_SRC','\ndef _time_variant'),
      ('tg_',p+'dev/parked/cand_tma_grouped.py','\nimport triton\nimport triton.language as tl','\ndef _tg_router_weights'),
      ('ma_',p+'baseline.py',None,None),
      ('fx_','problems/muse_decode_layer/moe_tune.py',None,'\ndef _graph_time'),
    ]
    for prefix,path,start,end in sources:
        s=segment(path,start,end)
        if prefix=='v19_':s+='\nTRACE_STRIDE = 10\n'
        if prefix=='tg_':
            # Keep only raw lossless repacker and grouped implementation, excluding copied incumbent/fixture.
            a=s.index('\ndef _rms('); b=s.index('TG_CUDA =')
            s=s[:a]+'\n'+s[b:]
            s=s.replace('_tg_incumbent_prepare = prepare','').replace('_tg_incumbent_kernel = kernel_fn','')
        if prefix=='hu_':
            s=s.replace('_prepare_native = _prepare_v9','').replace('_kernel_native = _kernel_v9','')
        if prefix in ('hu_','ho_'):
            s=s.replace('self.compile(range(1, PRECOMPILED_MAX_BS + 1))','self.compile((8,16,32,128,256,512,753))')
        parts += [f'# Copied from {path}, source sha256 {hashlib.sha256((ROOT/path).read_bytes()).hexdigest()}\n',namespace(s,prefix)]
    header='''"""H200 MoE matrix. Generated by build_moe_real_routing.py; edit the driver there or in moe_real_routing_driver.py.
R=decode-style aligned router using moe_tune.make_fixture (not the judge-selected decode router seed).
B=official standalone MoE routing generator. Times are graph replay GPU us (no fixed-cost subtraction).
Packed NVFP4 remains packed in candidates; BF16 grouped_mm is a reference-only dequantized weight bank.
"""\n'''
    out=HERE/'moe_real_routing.py'
    out.write_text(header+'\n'.join(parts)+'\n'+(HERE/'moe_real_routing_driver.py').read_text())
    print(out, out.stat().st_size,hashlib.sha256(out.read_bytes()).hexdigest())

if __name__=='__main__':build()
