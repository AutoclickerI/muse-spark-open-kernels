def pr_prepare(weights: pr_Weights):
    pr__module()
    state = {name: w.contiguous() for name, w in weights.items() if name != "router"}
    router = weights["router"].float().contiguous()
    hi = router.to(torch.bfloat16)
    lo = (router - hi.float()).to(torch.bfloat16)
    state["router_hi"] = hi.contiguous()
    state["router_lo"] = lo.contiguous()
    state["mod"] = pr__module()
    return state


def pr_skinny_gemm(x: torch.Tensor, w: torch.Tensor, n: int, layer: str, w_lo: torch.Tensor | None = None,
                out_dtype=torch.bfloat16) -> torch.Tensor:
    m = x.shape[0]
    nt = pr__nt(min(m, pr_SKINNY_MAX_M))
    tr, u, wn, wk, ks, xp = pr_CONFIGS[(layer, nt)]
    out = torch.empty((m, n), dtype=out_dtype, device=x.device)
    pr__module().skinny(w, w if w_lo is None else w_lo, x, out, n, nt, tr, u, wn, wk, ks, w_lo is not None, xp, 0)
    return out


def pr_kernel_fn(data: pr_Inputs, state) -> torch.Tensor:
    x = data["x"]
    cfg = data["config"]
    layer, n = cfg["layer"], cfg["n"]
    m = x.shape[0]
    if layer == "router":
        return pr_skinny_gemm(x, state["router_hi"], n, layer, state["router_lo"], torch.float32)
    if m <= pr_SKINNY_MAX_M:
        return pr_skinny_gemm(x, state[layer], n, layer)
    return F.linear(x, state[layer][:n])

